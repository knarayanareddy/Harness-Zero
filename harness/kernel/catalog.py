@dataclass(frozen=True)
class DeclaredSetting:
    key: str
    namespace: str
    owner: str
    prop: dict[str, Any]
    alias: bool = False


def plugin_schema_files(repo_root: Path = REPO_ROOT) -> list[tuple[Path, dict[str, Any], str]]:
    """Every ``settings.schema.json`` a built-in plugin ships, with the plugin that owns it."""
    out: list[tuple[Path, dict[str, Any], str]] = []
    plugins_dir = repo_root / "harness" / "plugins"
    for manifest_path in sorted(plugins_dir.glob("*/*/harness_plugin.toml")):
        try:
            manifest = PluginManifest.load(manifest_path)
        except Exception:  # noqa: BLE001 - a broken manifest is the plugin check's problem, not ours
            continue
        if not manifest.settings_schema:
            continue
        path = manifest_path.parent / manifest.settings_schema
        if not path.is_file():
            continue
        doc = json.loads(path.read_text(encoding="utf-8"))
        out.append((path, doc, manifest.name))
    return out


def declared_settings(repo_root: Path = REPO_ROOT) -> dict[str, DeclaredSetting]:
    """The full declared settings surface: ``{full_key: DeclaredSetting}``.

    Mirrors what the loader registers (``PluginRegistry._register_settings_schema``): the kernel
    namespace plus each plugin's own namespace, its compatibility aliases and its secret keys.
    """
    declared: dict[str, DeclaredSetting] = {}

    for key, prop in flatten_schema_properties(KERNEL_SCHEMA.get("properties", {})).items():
        declared[f"kernel.{key}"] = DeclaredSetting(f"kernel.{key}", "kernel", "kernel", prop)

    for _, doc, plugin in plugin_schema_files(repo_root):
        props = doc.get("properties", {})
        namespace = doc.get("x-namespace") or f"plugins.{plugin}"
        for key, prop in flatten_schema_properties(props).items():
            full = f"{namespace}.{key}"
            declared[full] = DeclaredSetting(full, namespace, plugin, prop)
        for alias, mapping in (doc.get("x-alias-namespaces") or {}).items():
            for alias_key, source in mapping.items():
                prop = props.get(source)
                if not isinstance(prop, dict):
                    continue
                full = f"{alias}.{alias_key}"
                declared.setdefault(full, DeclaredSetting(full, alias, plugin, prop, alias=True))
        for secret, meta in (doc.get("x-secrets") or {}).items():
            full = f"secrets.{secret}"
            prop = {"type": "string", "title": f"{secret} (secret)"}
            if isinstance(meta, dict):
                prop.update(meta)
            declared.setdefault(full, DeclaredSetting(full, "secrets", plugin, prop))
    return declared


def open_prefixes(declared: dict[str, DeclaredSetting]) -> tuple[str, ...]:
    """Declared *containers* whose children are user keys (``additionalProperties`` set)."""
    out: list[str] = []
    for key, entry in declared.items():
        prop = entry.prop
        if prop.get("type") == "object" and prop.get("additionalProperties") not in (None, False):
            out.append(key)
    return tuple(sorted(out, key=len, reverse=True))


@dataclass(frozen=True)
class SettingRead:
    key: str
    source: str  # repo-relative file:line
    plugin: str | None
    dynamic: bool  # read through an f-string suffix


def _owning_plugin(rel_path: Path) -> str | None:
    parts = rel_path.parts
    if len(parts) >= 4 and parts[0] == "harness" and parts[1] == "plugins":
        try:
            manifest = PluginManifest.load(REPO_ROOT / Path(*parts[:4]) / "harness_plugin.toml")
        except Exception:  # noqa: BLE001
            return None
        return manifest.name
    return None


def setting_reads(repo_root: Path = REPO_ROOT) -> list[SettingRead]:
    """Every literal settings read in the shipped code, resolved to the key it becomes at runtime.

    The resolution mirrors ``PluginSettingsView.get``: inside a plugin, a key that does not already
    start with ``kernel.``/``plugins.`` is read relative to that plugin's own namespace — a bare read
    of ``servers`` in ``bridge-mcp-client`` really is ``plugins.bridge-mcp-client.servers``. Outside
    plugins (kernel, CLI, frontends) keys are absolute. Skipping that step is how provider base URLs
    ended up configurable under a key the store never looked at.

    This module is excluded: its docstrings quote reads to explain the rule, and prose is not a call
    site.
    """
    reads: list[SettingRead] = []
    here = Path(__file__).name
    for path in sorted((repo_root / "harness").rglob("*.py")):
        if "__pycache__" in path.parts or path.name == here:
            continue
        rel = path.relative_to(repo_root)
        in_plugin = rel.parts[:2] == ("harness", "plugins")
        plugin = _owning_plugin(rel) if in_plugin else None
        text = path.read_text(encoding="utf-8")
        for match in SETTING_READ_RE.finditer(text):
            if match.group("recv") == "turn":
                continue
            raw = match.group("key")
            key = raw.rstrip(".")
            if not re.search(r"[a-z0-9]", key):
                continue  # prose, not a key
            if in_plugin and plugin and not key.startswith(("kernel.", "plugins.")):
                key = f"plugins.{plugin}.{key}"
            line = text[: match.start()].count("\n") + 1
            reads.append(SettingRead(key, f"{rel}:{line}", plugin, raw.endswith(".")))
    return reads


def settings_report(repo_root: Path = REPO_ROOT) -> dict[str, Any]:
    """Undeclared reads (must be zero) and declared-but-unread keys (informational)."""
    declared = declared_settings(repo_root)
    opens = open_prefixes(declared)
    reads = setting_reads(repo_root)

    def is_declared(key: str) -> bool:
        if key in declared:
            return True
        return any(key.startswith(f"{prefix}.") for prefix in opens)

    undeclared = sorted({(r.source, r.key) for r in reads if not is_declared(r.key)})
    used = {r.key for r in reads}

    def is_used(entry: DeclaredSetting) -> bool:
        if entry.key in used:
            return True
        return any(u.startswith(f"{entry.key}.") for u in used)

    dead = sorted(k for k, e in declared.items() if not e.alias and "x-ui" in e.prop and not is_used(e))
    return {
        "declared": len(declared),
        "reads": len(reads),
        "undeclared": [{"where": where, "key": key} for where, key in undeclared],
        "never_read": dead,
    }


