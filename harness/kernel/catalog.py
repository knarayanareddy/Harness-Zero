# Namespaces whose leaves a plugin reads through its own SettingsView prefix.
_ROOT_NAMESPACES = ("kernel", "plugins", "providers", "extensions", "secrets", "models")

# `settings.get(...)`, `ctx.settings.get(f"...")` and friends — but *not* `turn.settings.get(...)`,
# which is the per-turn override dict on a TurnRequest and has nothing to do with the store.
SETTING_READ_RE = re.compile(
    r"""(?:(?P<recv>[A-Za-z_]\w*)\.)?settings\.get\(\s*f?["'](?P<key>[a-zA-Z0-9_.\-]+)["']"""
)
_CLIENT_ON_RE = re.compile(r"""\.on\(\s*['"]([a-z_.]+)['"]""")
_CLIENT_CMD_RE = re.compile(r"""command\(\s*['"]([a-z_.]+)['"]""")
_ROUTE_RE = re.compile(r"""add_(?:get|post|put|delete)\(\s*["']([^"']+)["']""")
_DATA_ATTR_RE = re.compile(r"""data-(command|setting|action|event)\s*=\s*["']?([a-zA-Z0-9_.\-]+)""")


