ALL_CHECKS = ("drift", "settings", "readmes", "ui", "scenarios", "refs")


@dataclass
class CheckReport:
    results: dict[str, dict[str, Any]]

    @property
    def ok(self) -> bool:
        return all(r["status"] != "fail" for r in self.results.values())

    def render(self, fmt: str = "text") -> str:
        if fmt == "json":
            return json.dumps(self.results, indent=2, sort_keys=True)
        out = []
        for name, r in self.results.items():
            mark = {"pass": "ok  ", "fail": "FAIL", "warn": "warn"}[r["status"]]
            out.append(f"[{mark}] {name}: {r['detail']}")
            if r["status"] != "pass":
                for line in r.get("lines", [])[:20]:
                    out.append(f"        {line}")
        return "\n".join(out)


def _check_drift(cat: dict[str, Any], root: Path) -> dict[str, Any]:
    bad = []
    for name in CATALOG_DOCS:
        path = root / CATALOG_DIR / name
        expected = render_markdown(cat, name)
        if not path.is_file():
            bad.append(f"{path.relative_to(root)} is missing")
        elif path.read_text(encoding="utf-8") != expected:
            bad.append(f"{path.relative_to(root)} is stale — run `harness catalog gen`")
    jpath = root / CATALOG_DIR / "catalog.json"
    if not jpath.is_file() or json.loads(jpath.read_text(encoding="utf-8")) != json.loads(json.dumps(cat, sort_keys=True)):
        bad.append(f"{jpath.relative_to(root)} is stale — run `harness catalog gen`")
    spath = root / "docs" / "events.schema.json"
    if not spath.is_file() or json.loads(spath.read_text(encoding="utf-8")) != events_schema():
        bad.append("docs/events.schema.json is stale — run `harness events schema`")
    if bad:
        return {"status": "fail", "detail": f"{len(bad)} stale file(s)", "lines": bad}
    return {"status": "pass", "detail": "generated docs and event schema match the booted kernel", "lines": []}


def _check_settings(root: Path) -> dict[str, Any]:
    report = settings_report(root)
    if report["undeclared"]:
        return {
            "status": "fail",
            "detail": f"{len(report['undeclared'])} setting read(s) with no declaration",
            "lines": [f"{u['where']} reads {u['key']} — declare it in the plugin's settings.schema.json or KERNEL_SCHEMA" for u in report["undeclared"]],
        }
    dead = report["never_read"]
    if dead:
        return {"status": "warn", "detail": f"{report['declared']} declared, {report['reads']} reads, {len(dead)} never read", "lines": dead}
    return {"status": "pass", "detail": f"{report['declared']} declared settings, all reads declared", "lines": []}


def _check_readmes(cat: dict[str, Any], root: Path) -> dict[str, Any]:
    incomplete = []
    for p in cat["plugins"]:
        have = p["readme_sections"]
        if len(have) < len(README_SECTIONS):
            missing = [s for s in README_SECTIONS if s not in have]
            incomplete.append(f"{p['name']}: missing {', '.join(missing)} ({p['readme'] or 'no README.md'})")
    if incomplete:
        status = "warn"  # the runtime does not depend on this; WS-05 closes it
        return {"status": status, "detail": f"{len(incomplete)}/{len(cat['plugins'])} plugin READMEs incomplete", "lines": incomplete}
    return {"status": "pass", "detail": "every plugin README carries the five sections", "lines": []}


def _check_ui(cat: dict[str, Any]) -> dict[str, Any]:
    """The client may not claim UI that the kernel does not offer.

    This check used to be advisory about one thing (an event with no client renderer, which is a design choice —
    a stream delta has nothing to paint). The three facts below are not choices: a tab in the markup that no
    feature declared, a declared panel whose command does not dispatch, and a control bound to a command the
    table does not contain. Each one is a bug a user finds by clicking, which is why they gate the build instead
    of only appearing in `docs/catalog/UI_CONTRACT.md`.
    """
    ui = cat["ui"]
    problems: list[tuple[str, list[str]]] = []
    if ui["unknown_client_commands"]:
        problems.append(("the web client calls commands that are not registered", [f"POST /commands/{c}" for c in ui["unknown_client_commands"]]))
    if ui["undocumented_tabs"]:
        problems.append(
            ("`data-tab` in the client with no `[ui]` declaration (delete the pane or declare it)",
             [f'data-tab="{t}"' for t in ui["undocumented_tabs"]])
        )
    if ui["unbacked_panels"]:
        problems.append(
            ("declared panels whose command is not dispatchable",
             [f"{panel['id']} → {panel['command']} (declared by {panel['plugin']})" for panel in ui["unbacked_panels"]])
        )
    dangling = [b["command"] for b in ui["data_command_bindings"] if not b["registered"]]
    if dangling:
        problems.append(("`data-command` bindings to commands the kernel does not expose", [f"data-command=\"{c}\"" for c in dangling]))
    if problems:
        # One heading per problem, then its offending items — `--check` prints these verbatim.
        lines = []
        for label, items in problems:
            lines.append(f"{label}:")
            lines.extend(f"  {item}" for item in items)
        return {"status": "fail", "detail": f"{len(problems)} UI contract problem(s)", "lines": lines}
    unrendered = ui["events_without_renderer"]
    return {
        "status": "pass",
        "detail": (
            f"client calls {len(ui['client_commands'])} registered commands and mounts {len(ui['panels'])} "
            f"declared panel(s); {len(unrendered)} event(s) are bus-only by design; "
            f"{len(ui['kinds_without_renderer'])} durable kind(s) are markers with nothing to paint"
        ),
        "lines": [],
    }


def _check_scenarios(cat: dict[str, Any], strict: bool) -> dict[str, Any]:
    cov = cat["coverage"]
    gaps = cov["tools_uncovered"] + [f"command {c}" for c in cov["commands_unexercised"]]
    if gaps and strict:
        return {"status": "fail", "detail": f"{len(gaps)} uncovered", "lines": gaps}
    if gaps:
        return {"status": "warn", "detail": f"{len(cov['tools_covered'])}/{len(cov['tools_covered']) + len(cov['tools_uncovered'])} tools and {len(cov['commands_exercised'])} commands covered by scenarios; {len(gaps)} gaps", "lines": gaps}
    return {"status": "pass", "detail": "every tool and web command appears in a scenario", "lines": []}


_REF_RE = re.compile(r"`([a-z][a-z0-9_-]*(?:\.[a-z0-9_-]+)+)`")


def _check_refs(cat: dict[str, Any], root: Path) -> dict[str, Any]:
    """Namespaced identifiers in the docs must exist (WS-02 `refs`, scoped to settings keys)."""
    allow = set()
    allow_path = root / CATALOG_DIR / "refs.allow"
    if allow_path.is_file():
        allow = {
            line.strip()
            for line in allow_path.read_text(encoding="utf-8").splitlines()
            if line.strip() and not line.startswith("#")
        }
    known = (
        {s["key"] for s in cat["settings"]}
        | {s["namespace"] for s in cat["settings"]}
        | {c["name"] for c in cat["commands"]}
        | {e["type"] for e in cat["events"]}
    )
    # `secrets.py`, `settings.json`, `app.js` … are files, not identifiers the catalog owns.
    file_suffixes = (".py", ".js", ".mjs", ".json", ".toml", ".md", ".css", ".html", ".yaml", ".yml", ".txt", ".cjs")
    bad = []
    for doc in [root / "README.md", root / "CHANGELOG.md", *sorted((root / "docs").rglob("*.md"))]:
        if not doc.is_file() or "research" in doc.parts or doc.parts[:2] == ("docs", "catalog"):
            continue  # the catalogue is the catalog: it does not reference itself
        for ident in _REF_RE.findall(doc.read_text(encoding="utf-8")):
            if ident in allow or ident in known or ident.endswith(file_suffixes):
                continue
            if ident.split(".", 1)[0] in {"kernel", "plugins", "providers", "secrets", "extensions"}:
                bad.append(f"{doc.relative_to(root)}: `{ident}` is not a declared setting, command or event")
    if bad:
        return {"status": "warn", "detail": f"{len(bad)} doc reference(s) not in the catalog", "lines": sorted(set(bad))}
    return {"status": "pass", "detail": "every namespaced identifier in the docs resolves", "lines": []}


async def run_checks(root: Path | None = None, sections: tuple[str, ...] = ALL_CHECKS, *, strict_scenarios: bool = False) -> CheckReport:
    repo = Path(root) if root else REPO_ROOT
    cat = await build_catalog(repo_root=repo)
    results: dict[str, dict[str, Any]] = {}
    for section in sections:
        if section == "drift":
            results[section] = _check_drift(cat, repo)
        elif section == "settings":
            results[section] = _check_settings(repo)
        elif section == "readmes":
            results[section] = _check_readmes(cat, repo)
        elif section == "ui":
            results[section] = _check_ui(cat)
        elif section == "scenarios":
            results[section] = _check_scenarios(cat, strict_scenarios)
        elif section == "refs":
            results[section] = _check_refs(cat, repo)
        else:
            raise ValueError(f"unknown catalog section {section!r}")
    return CheckReport(results)
