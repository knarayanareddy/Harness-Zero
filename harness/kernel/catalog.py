def _rel(path: Any, repo_root: Path) -> str:
    p = Path(str(path))
    try:
        return str(p.relative_to(repo_root))
    except ValueError:
        return "<outside-repo>"


def _first_line(text: str | None) -> str:
    if not text:
        return ""
    for line in str(text).strip().splitlines():
        if line.strip():
            return line.strip().rstrip(".") + "."
    return ""


def _scan_producers(repo_root: Path, etype: str) -> list[str]:
    """Heuristic: files that name this event type *at* a publish site.

    Deliberately dumb and labelled as such in the generated docs — the payload dataclasses are the
    contract, this only answers "who emits it". The match is local (a window around each occurrence)
    rather than file-wide, because a module that merely enumerates event names is not a producer: the
    record-kind vocabulary in `harness/sdk/types.py` deliberately spells them the same as the durable
    events, and a file-wide scan read that as a publisher of all of them.
    """
    literal = f'"{etype}"'
    markers = ("Event(", "publish", "type=", '"type":')
    hits: list[str] = []
    for path in sorted((repo_root / "harness").rglob("*.py")):
        if "__pycache__" in path.parts or path.name == "events.py":
            continue
        text = path.read_text(encoding="utf-8")
        found = False
        start = text.find(literal)
        while start != -1:
            window = text[max(0, start - 120) : start + 120]
            if any(marker in window for marker in markers):
                found = True
                break
            start = text.find(literal, start + 1)
        if found:
            hits.append(str(path.relative_to(repo_root)))
    return hits[:4]


async def build_catalog(runtime: Any = None, repo_root: Path | None = None) -> dict[str, Any]:
    """The catalog as the running kernel sees it (boots hermetically when given no runtime)."""
    root = Path(repo_root) if repo_root else REPO_ROOT
    if runtime is None:  # pragma: no cover - CLI path
        import tempfile

        from harness.kernel.bootstrap import bootstrap_kernel

        ws = Path(tempfile.mkdtemp(prefix="harness-catalog-"))
        conf = ws / ".harness"
        conf.mkdir(parents=True, exist_ok=True)
        runtime = await bootstrap_kernel(workspace=ws, config_dir=conf)
        owned = True
    else:
        owned = False

    registry = runtime.registry
    commands = runtime.commands

    # ---- plugins ----
    rows: list[dict[str, Any]] = []
    plugin_info = {p["name"]: p for p in await commands.plugins_list()}
    for name, dp in sorted(registry.discovered.items()):
        entry = plugin_info.get(name, {})
        directory = plugin_dir(dp)
        schema_file = None
        if dp.manifest.settings_schema:
            candidate = directory / dp.manifest.settings_schema
            if candidate.is_file():
                schema_file = _rel(candidate, root)
        readme = directory / "README.md"
        sections = []
        if readme.is_file():
            have = readme.read_text(encoding="utf-8")
            sections = [s for s in README_SECTIONS if f"## {s}" in have]
        rows.append(
            {
                "name": name,
                "version": dp.manifest.version,
                "summary": dp.manifest.summary,
                "family": directory.parent.name,
                "tier": dp.tier.value,
                "loaded": registry.is_loaded(name),
                "provides": [str(p) for p in dp.manifest.provides],
                "capabilities": entry.get("capabilities", []),
                "requires": list(dp.manifest.requires),
                "entry": dp.manifest.entry,
                "path": _rel(directory, root),
                "settings_schema": schema_file,
                "readme": _rel(readme, root) if readme.is_file() else None,
                "readme_sections": sections,
            }
        )

    # ---- tools ----
    # The owning plugin lives in the registry's tool table (spec.plugin is a caller-provided hint
    # that the built-in tools leave empty), so read the origin from there.
    origins = {name: origin for name, (_spec, _handler, origin) in registry.tools.items()}
    tools = []
    for spec in sorted(registry.get_all_tool_specs(), key=lambda s: s.name):
        tools.append(
            {
                "name": spec.name,
                "plugin": origins.get(spec.name) or spec.plugin,
                "risk_class": spec.risk_class.value,
                "timeout_s": spec.timeout_s,
                "streams_output": spec.streams_output,
                "annotations": spec.annotations.to_dict(),
                "description": _first_line(spec.description),
                "input_properties": sorted((spec.input_schema or {}).get("properties", {})),
                "required": sorted((spec.input_schema or {}).get("required", [])),
            }
        )

    # ---- settings ----
    declared = declared_settings(root)
    ui_props = (await commands.settings_schema())["properties"]
    settings_rows = []
    for key, entry in sorted(declared.items()):
        prop = with_ui_defaults(entry.prop, entry.namespace)
        settings_rows.append(
            {
                "key": key,
                "type": prop.get("type"),
                "default": json.dumps(prop.get("default")),
                "title": prop.get("title", ""),
                "group": prop.get("x-ui", {}).get("group"),
                "widget": prop.get("x-ui", {}).get("widget"),
                "owner": registry.settings_owner(entry.namespace) if hasattr(registry, "settings_owner") else entry.owner,
                "namespace": entry.namespace,
                "alias": entry.alias,
                "in_ui": key in ui_props,
            }
        )

    # ---- events ----
    client = root / "harness" / "frontends" / "web" / "static"
    app_js = (client / "app.js").read_text(encoding="utf-8")
    renderers = set(_CLIENT_ON_RE.findall(app_js))
    scenario_events: dict[str, list[str]] = {}
    for golden in sorted((root / "tests" / "scenarios").glob("*/golden/events.json")):
        types = {e.get("type") for e in json.loads(golden.read_text(encoding="utf-8"))}
        for t in types:
            scenario_events.setdefault(str(t), []).append(golden.parents[1].name)
    events = []
    for etype, payload in sorted(EVENT_PAYLOADS.items()):
        events.append(
            {
                "type": etype,
                "payload": payload.__name__,
                "fields": sorted(getattr(payload, "__dataclass_fields__", {}) or {}),
                "producers": _scan_producers(root, etype),
                "client_renderer": "app.js" if etype in renderers else "none (live only)",
                # WS-04: whether the event has a counterpart in the session log, and which record kind it
                # is. `durable` is derived from `record_kind` (see `harness.sdk.events.EventPayload`), so
                # this cannot claim durability the payload does not.
                "durable": payload.record_kind is not None,
                "record_kind": payload.record_kind,
                "transient": bool(payload.transient),
                "scenarios": sorted(scenario_events.get(etype, [])),
            }
        )

    # ---- record kinds (the session log's vocabulary, WS-04) ----
    # No source scan here: which kinds a marker path writes is not visible in a literal, so the table says
    # what is provable instead — the payload classes that name a kind, and the recorded transcripts that
    # actually hold one. A kind with no scenario is declared but unused (WS-10's reserved rows).
    from harness.kernel.transcript import MESSAGE_KINDS
    from harness.sdk.types import RECORD_KINDS

    kind_scenarios: dict[str, set[str]] = {}
    for golden in sorted((root / "tests" / "scenarios").glob("*/golden/transcript.json")):
        name = golden.parents[1].name
        for rec in json.loads(golden.read_text(encoding="utf-8")):
            kind_scenarios.setdefault(str(rec.get("kind", "")), set()).add(name)
    record_kinds = [
        {
            "kind": kind,
            # `derive_messages`' filter: a model-visible kind is one that reaches the next ModelRequest.
            "model_visible": kind in MESSAGE_KINDS,
            "durable_events": sorted(e for e, pl in EVENT_PAYLOADS.items() if pl.record_kind == kind),
            "scenarios": sorted(kind_scenarios.get(kind, set())),
        }
        for kind in RECORD_KINDS
    ]

    # ---- commands ----
    client_cmds = set(_CLIENT_CMD_RE.findall((client / "api.js").read_text(encoding="utf-8")))
    cmds = []
    for name in BUILTIN_COMMANDS:
        handler = getattr(commands, name.replace(".", "_").replace("-", "_"), None)
        doc = inspect.getdoc(handler) if handler else ""
        args = []
        if handler:
            args = [
                {"name": p.name, "type": (p.annotation if isinstance(p.annotation, str) else getattr(p.annotation, "__name__", "Any")),
                 "default": None if p.default is inspect.Parameter.empty else repr(p.default)}
                for p in inspect.signature(handler).parameters.values()
                if p.kind in (p.POSITIONAL_OR_KEYWORD, p.KEYWORD_ONLY)
            ]
        cmds.append(
            {
                "name": name,
                "alias": "_" in name and name.replace("_", ".", 1) in set(BUILTIN_COMMANDS),
                "handler": f"harness/kernel/commands.py:{getattr(handler, '__name__', '')}" if handler else "missing",
                "summary": _first_line(doc),
                "args": args,
                "called_by_web_client": name in client_cmds,
            }
        )

    # ---- web client / routes ----
    server_py = (root / "harness" / "frontends" / "web" / "server.py").read_text(encoding="utf-8")
    routes = sorted({m for m in _ROUTE_RE.findall(server_py)})
    ui_attrs: dict[str, list[str]] = {}
    for js in sorted(client.glob("*.js")) + [client / "index.html"]:
        for kind, value in _DATA_ATTR_RE.findall(js.read_text(encoding="utf-8")):
            ui_attrs.setdefault(kind, []).append(f"{js.name}:{value}")
    builtins = set(BUILTIN_COMMANDS)

    # ---- UI contributions (WS-05): what the client mounts, and whether the markup agrees ----
    # The kernel's answer (`ui.contributions`) and the static HTML are compared rather than one derived from
    # the other: a tab in `index.html` with no declaration is a pane nobody owns, and a declared panel with no
    # markup is a feature promising a tab it never renders. Neither looks wrong in isolation, so the pairing
    # is what makes the evidence.
    contributions = await commands.ui_contributions()
    commands_exposed = {row["name"] for row in await commands.commands_list() if row["exposed"]}
    html_text = (client / "index.html").read_text(encoding="utf-8")
    js_text = "\n".join(js.read_text(encoding="utf-8") for js in sorted(client.rglob("*.js")))
    markup = html_text + js_text
    tabs_in_html = _static_values(re.findall(_TAB_RE, markup))
    declared_panels = {panel["id"]: panel for panel in contributions["panels"]}
    bound = _static_values(re.findall(_DATA_COMMAND_RE, markup))
    # Kinds the client has a case for: the `renderRecord` switch today, one module per kind after WS-05b — both
    # shapes are read, so the count does not move when the code moves.
    painted = set(re.findall(_RENDER_CASE_RE, js_text))
    renderer_dir = client / "renderers"
    renderer_modules = sorted(f.stem for f in renderer_dir.glob("*.js")) if renderer_dir.is_dir() else []
    painted |= set(renderer_modules)
    declared_renderers = {r["kind"] for r in contributions["record_renderers"]}
    durable = [r["kind"] for r in record_kinds if r["durable_events"]]
    ui = {
        "routes": routes,
        "client_commands": sorted(client_cmds),
        "unknown_client_commands": sorted(c for c in client_cmds if c not in builtins),
        "data_attributes": {k: sorted(set(v)) for k, v in sorted(ui_attrs.items())},
        "events_without_renderer": sorted(t for t, e in ((e["type"], e) for e in events) if e["client_renderer"].startswith("none")),
        "panels": [{**panel, "in_client_markup": panel["id"] in tabs_in_html} for panel in contributions["panels"]],
        "undocumented_tabs": [t for t in tabs_in_html if t not in declared_panels],
        "unbacked_panels": contributions["unbacked_panels"],
        "data_command_bindings": [{"command": c, "registered": c in commands_exposed} for c in bound],
        "client_modules": contributions["client_modules"],
        "renderer_modules": renderer_modules,
        "durable_kinds": sorted(durable),
        "settings_groups": contributions["settings_groups"],
        "kinds_without_renderer": sorted(k for k in durable if k not in painted and k not in declared_renderers),
    }

    # ---- scenarios ----
    scenarios = []
    for path in sorted((root / "tests" / "scenarios").glob("*/scenario.yaml")):
        text = path.read_text(encoding="utf-8")
        tools_called: list[str] = []
        m = re.search(r"tools_called:\s*\[([^\]]*)\]", text)
        if m:
            tools_called = sorted({t.strip() for t in m.group(1).split(",") if t.strip()})
        turn_count = len(re.findall(r"^\s*-\s+prompt:", text, re.M))
        scenarios.append(
            {
                "name": path.parent.name,
                "kind": (re.search(r"^kind:\s*(\S+)", text, re.M) or [None, "?"])[1],
                "summary": _first_line((re.search(r"^summary:\s*(.+)$", text, re.M) or [None, ""])[1]),
                "turns": turn_count,
                "tools_called": tools_called,
            }
        )
    tool_names = {t["name"] for t in tools}
    covered_tools = {t for sc in scenarios for t in sc["tools_called"]}
    coverage = {
        "tools_covered": sorted(covered_tools & tool_names),
        "tools_uncovered": sorted(tool_names - covered_tools),
        "commands_exercised": sorted(client_cmds & builtins),
        "commands_unexercised": sorted(builtins - client_cmds),
    }

    if owned:
        await registry.unload_all()

    return {
        "generated_by": "harness catalog gen",
        "version": _version(),
        "plugins": rows,
        "tools": tools,
        "settings": settings_rows,
        "events": events,
        "cards": {k: sorted(v) for k, v in sorted(CARD_FIELDS.items())},
        "commands": cmds,
        "record_kinds": record_kinds,
        "ui": ui,
        "scenarios": scenarios,
        "coverage": coverage,
        "provenance": {
            "plugins": "registry.discovered of a booted kernel",
            "tools": "registry.get_all_tool_specs()",
            "settings": "registered JSON Schemas (kernel + plugin settings.schema.json)",
            "events": "harness.sdk.events.EVENT_PAYLOADS; producers are a heuristic source scan",
            "commands": "harness.kernel.commands.BUILTIN_COMMANDS",
            "record_kinds": "harness.sdk.types.RECORD_KINDS + harness.kernel.transcript.MESSAGE_KINDS + "
                            "EventPayload.record_kind + tests/scenarios/*/golden/transcript.json",
            "ui": "static parse of the shipped client and the aiohttp route table",
            "scenarios": "tests/scenarios/*/scenario.yaml + golden/events.json",
        },
    }


def _version() -> str:
    from harness import __version__

    return __version__


