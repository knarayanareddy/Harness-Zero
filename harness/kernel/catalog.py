"""Generated catalogs and freshness checks (WS-02).

``harness catalog gen`` renders ``docs/catalog/*`` and ``docs/events.schema.json`` from a kernel that
has actually been booted — the plugin registry, its tool specs, the settings schemas its plugins
registered, the SDK event/card catalogues, the command table, the shipped web client and the scenario
goldens. ``harness catalog --check`` then re-renders in memory and fails on any difference, so a
reference document cannot describe a system that no longer exists (the failure mode that produced
reviews v0.2.0/v0.2.1/158c836).

Two rules keep this module honest:

* It never invents a fact. Every row is read from the object that serves it at runtime; anything
  derived by scanning source text is labelled ``heuristic`` in the generated document and in
  ``catalog.json``.
* It is deterministic: sorted output, repo-relative paths, no timestamps, no absolute tmp paths — so
  the generated files are reviewable diffs, not noise.
"""

